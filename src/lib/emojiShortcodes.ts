export const EMOJI_LIST: EmojiEntry[] = RAW.map(([shortcode, char]) => ({ shortcode, char }));

/**
 * Search emoji list by shortcode prefix/substring.
 * Returns up to `limit` matches, prefix matches first.
 */
export function searchEmojis(query: string, limit = 8): EmojiEntry[] {
  if (!query) return [];
  const q = query.toLowerCase();
  const prefix: EmojiEntry[] = [];
  const contains: EmojiEntry[] = [];
  for (const entry of EMOJI_LIST) {
    if (entry.shortcode.startsWith(q)) prefix.push(entry);
    else if (entry.shortcode.includes(q)) contains.push(entry);
    if (prefix.length + contains.length >= limit * 2) break;
  }
  return [...prefix, ...contains].slice(0, limit);
}
